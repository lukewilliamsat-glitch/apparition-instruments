assert.match(domainMigration,/primary key \(assembly_id, position\)/);
assert.match(domainMigration,/kit_price_quantity integer/);
for(const table of ['admin_members','components','component_internal','inventory','assemblies','assembly_bom','kit_definitions','kit_definition_internal','kit_permitted_components'])assert.match(migration,new RegExp('alter table public\\.'+table+' enable row level security'));
