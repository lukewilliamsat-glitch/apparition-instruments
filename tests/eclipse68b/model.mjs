import assert from 'node:assert/strict';
import {applyPreset,financeSummary,safePart,suggestedPreset,updateFee,withSnapshot,withTrustedFacts} from '../../dist/admin/orders/eclipse-model.mjs';
import {financeDraft} from '../../dist/admin/orders/finance-ui.mjs';
import {profitabilityReportV2} from '../../dist/admin/orders/economics-v2.mjs';
import {exampleDocument,exampleOrders,exampleLibrary} from './examples.mjs';
const [e,w]=exampleOrders,preset='small-component';
const direct=withTrustedFacts(financeDraft(w),w),ebay=financeDraft(e);
assert.equal(safePart(ebay),750);
assert.equal(direct.actualPaidMinor,1149);
assert.equal(direct.marketplaceTaxMinor,0);
assert.equal(direct.tax.state,'unreviewed');
assert.equal(direct.lines[0].unitCostMicro,null);
assert.equal(direct.feesComplete,false);
assert.equal(financeSummary(direct).contribution,null);
assert.equal(ebay.marketplaceTaxMinor,null);
assert.equal(suggestedPreset(exampleLibrary,e),preset);
const original=exampleDocument(e);
assert.equal(financeSummary(original).contribution,622);
assert.equal(financeSummary(original).margin,'54.13');
assert.equal(financeSummary(original).status,'Estimated');
const website=exampleDocument(w);
assert.equal(financeSummary(website).contribution,717);
assert.equal(financeSummary(website).margin,'62.40');
assert.equal(financeSummary(website,false).contribution,null);
const revis=structuredClone(exampleLibrary);revis.revision++;revis.items[0].unitMinor=27;
assert.equal(applyPreset(original,revis,preset).costs.packaging.minor,37);
assert.equal(original.fulfilmentSnapshot.items[0].unitMinor,15);
assert.equal(original.costs.packaging.minor,25);
const actual=withSnapshot(original,original.fulfilmentSnapshot,'confirmed','Packaging receipt');
assert.equal(financeSummary(actual).status,'Complete');
assert.equal(financeSummary(actual).contribution,622);
assert.throws(()=>withSnapshot(original,original.fulfilmentSnapshot,'confirmed',''));
let withCredit=structuredClone(original);withCredit.fees[0].includes=['payment'];
assert.throws(()=>updateFee(withCredit,'payment',5,'estimated','Estimate'),/combined/);
assert.throws(()=>updateFee(original,'marketplace',5,'confirmed',''),/receipt/);
let refund=structuredClone(actual);refund.adjustments.push({kind:'refund',id:'linked-refund',state:'confirmed',minor:40,source:'Synthetic refund'});refund.tax={state:'confirmed',minor:20,source:'Synthetic seller tax calculation'};
assert.equal(financeSummary(refund).contribution,562);
assert.equal(financeSummary(refund).margin,'51.61');
assert.equal(profitabilityReportV2([{...e,finance:actual}],{from:'2026-10-01',to:'2026-10-31'}).groups[0].contributionMinor,622);
assert.equal(profitabilityReportV2([{...e,finance:actual}],{from:'2026-11-01'}).orders,0);
assert.equal(financeSummary(null).status,'Not recorded');
console.log('ECLIPSE: 27 focused calculation, estimate, immutable snapshot, reconciliation, and commercial-date assertions passed.');
