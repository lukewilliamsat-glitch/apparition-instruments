import assert from 'node:assert/strict';
import {randomUUID} from 'node:crypto';
import {readFileSync} from 'node:fs';
import {Window} from 'happy-dom';

const window=new Window({url:'https://example.test/admin/?view=assemblies'});
for(const setting of ['disableJavaScriptEvaluation','disableCSSFileLoading','disableJavaScriptFileLoading'])window.happyDOM.settings[setting]=true;
for(const key of ['window','document','location','Event','HTMLElement','Node'])Object.defineProperty(globalThis,key,{value:key==='window'?window:window[key],configurable:true,writable:true});
document.write(readFileSync(new URL('../dist/admin/index.html',import.meta.url),'utf8'));
const {initialComponents}=await import('../dist/admin/data.mjs');
const {lesPaulKitAssembly,normaliseKitDefinition}=await import('../dist/admin/assemblies.mjs');
const {setAssemblyRepository}=await import('../dist/admin/assembly-repository.mjs');
const {renderAssemblies}=await import('../dist/admin/assembly-ui.mjs');
const {configuredKitDefinitions,resolveKitComponent,availableKitValues}=await import('../dist/wiring-kits/kit-data.mjs');
const {kitAdminCandidates}=await import('../dist/wiring-kits/kit-component-discovery.mjs');
const unique=randomUUID(),maker='Unregistered '+unique,fixture=(category,specs)=>({id:randomUUID(),name:'Physical '+randomUUID(),sku:randomUUID(),manufacturer:maker,category,specs,active:true,inKits:true,stock:50,kitPrice:199});
const pot=fixture('potentiometers',{Resistance:'500kΩ',Taper:'Audio',Shaft:'Short',Type:'Standard'});
const bad=fixture('potentiometers',{Resistance:'511',Taper:'Audio',Shaft:'Short',Type:'Standard'});
const cap=fixture('capacitors',{Value:'47nF'}),bleed=fixture('treble-bleeds',{Topology:'Capacitor only'}),toggle=fixture('switches',{'Switch type':'3-Way Toggle',Positions:'3'}),jack=fixture('jacks',{'Jack type':'Mono'});
const records=[...initialComponents().map(c=>({...c,active:true,inKits:true,stock:10})),pot,bad,cap,bleed,toggle,jack];
let kit=structuredClone(lesPaulKitAssembly),saves=0;
kit.kitDefinition.permittedComponentIds.push('pot-short-alpha-a');
setAssemblyRepository({async list(){return [structuredClone(kit)];},async get(){return structuredClone(kit);},async save(input,id){assert.equal(id,kit.id);saves++;kit={...input,id,kitDefinition:normaliseKitDefinition(input.kitDefinition)};return structuredClone(kit);}});
await renderAssemblies('',records);
document.querySelector('[aria-label="Edit Les Paul Style Wiring Kit"]').click();
assert(document.querySelector('#assembly-dialog').open,'actual Admin editor opens');
const candidate=id=>[...document.querySelectorAll('#kit-permitted-components label')].find(label=>label.textContent.includes(id));
for(const item of [pot,cap,bleed,toggle,jack]){
 const label=candidate(item.id);assert(label,'actual Admin category candidate path misses '+item.category);
 assert(label.textContent.includes('AVAILABLE / ELIGIBLE'));
 assert.equal(label.closest('fieldset').querySelector('legend').textContent,({potentiometers:'Potentiometers',capacitors:'Tone Capacitors','treble-bleeds':'Treble Bleeds',switches:'Selector Switches',jacks:'Output Jacks'})[item.category]);
}
assert.match(candidate(bad.id).textContent,/CURRENTLY INELIGIBLE.*Nominal resistance must be explicitly 500kΩ.*511/);
assert(candidate(bad.id).querySelector('input').disabled);
assert(!kitAdminCandidates([{...pot,active:false}],[]).potentiometers.length);
const brandValue=[...document.querySelectorAll('#kit-builder-options label')].find(label=>label.textContent.includes(maker));assert(brandValue,'unknown brand must appear in Admin Builder options');
const mapping=[...document.querySelectorAll('#kit-variant-mappings label')].find(label=>label.textContent.includes(maker));assert(mapping,'new physical short variant must be derived');
assert.equal(mapping.querySelector('select').value,pot.id);
assert.equal([...document.querySelectorAll('#kit-variant-mappings label')].filter(label=>label.textContent.includes(maker)).length,1,'do not invent Long variant');
const before=configuredKitDefinitions(records,kit)['les-paul'];assert.equal(before.pots[maker],undefined);
candidate(pot.id).querySelector('input').click();
document.querySelector('#assembly-form').dispatchEvent(new Event('submit',{bubbles:true,cancelable:true}));
await new Promise(resolve=>setTimeout(resolve,0));
assert.equal(saves,1);assert(kit.kitDefinition.permittedComponentIds.includes(pot.id));
assert(!kit.kitDefinition.permittedComponentIds.includes(bad.id));
const after=configuredKitDefinitions(records,kit)['les-paul'];assert.equal(after.pots[maker].enabled,true);
assert.equal(resolveKitComponent(after,{pots:maker,shaft:'short'}).component.id,pot.id);
assert(!availableKitValues(after,'shaft',{pots:maker,shaft:'short'}).has('long'));
assert.equal(resolveKitComponent(after,{pots:maker,shaft:'long'}),null);
assert.equal(resolveKitComponent(after,{pots:'Alpha',shaft:'short'}).component.id,'pot-short-alpha-a');
assert.equal(after.pots[maker].enabled,true);
assert.equal(after.records.find(c=>c.id===pot.id).stock,50);
assert.equal(resolveKitComponent(after,{pots:maker,shaft:'short'}).component.kitPrice,199);
await window.happyDOM.abort();
console.log('P06A.1 actual Admin editor categories, ineligible reason, unknown brand permission/save, derived short mapping, customer resolution, stock, pricing and legacy Alpha passed.');
