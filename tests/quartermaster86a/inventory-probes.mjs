import assert from 'node:assert/strict';
const detail='select public.quartermaster86a_detail($1,$2)';
const change='select public.quartermaster86a_change($1,$2,$3,$4,$5,$6,$7)';
const register='select public.quartermaster86_register($1,$2,$3,$4,$5,$6,$7)';
const nil=null;
export async function inventoryProbes({db,call,write,uid,other,supplier}) {
 const sku='86A-LOT';
 const read=(batch=nil,member=2)=>call(member,detail,[sku,batch]);
 const registerArgs=[sku,'Admin mailer',[30,20,9],[34,24,13],10,2,'Initial'];
 await write(2,register,registerArgs);
 const run=(n,version,action,values={},batch=nil,member=2)=>write(member,change,
   [uid(n),sku,batch,version,action,'Isolated acceptance reason',values]);
 const revision=async(batch=nil)=>(await read(batch)).revision;
 const first=await revision();
 const rename={displaySku:'86A-UPDATED',title:'Changed mailer',description:'Revised',inner:[30,20,9],outer:[34,24,13],tare:10,reorder:3};
 assert.equal((await run(101,first,'edit',rename)).displaySku,'86A-UPDATED');
 assert.equal((await run(101,first,'edit',rename)).title,'Changed mailer');
 await assert.rejects(run(102,first,'archive'),{code:'40001'});
 await assert.rejects(write(2,register,['86A-UPDATED',...registerArgs.slice(1)]),{code:'23505'});
 await assert.rejects(read(nil,3),{code:'42501'});
 await assert.rejects(call(null,detail,[sku,nil],'anon'),{code:'42501'});
 const batch=uid(103);
 assert.equal((await run(103,await revision(),'opening',{supplier,reference:'86A-INITIAL',quantity:4,totalMinor:200})).physical,4);
 await assert.rejects(run(104,await revision(),'opening',{supplier,reference:'86A-SECOND',quantity:2,totalMinor:80}),{code:'23514'});
 assert.equal((await run(105,await revision(batch),'reference',{reference:'86A-CORRECTED'},batch)).batch.reference,'86A-CORRECTED');
 await assert.rejects(write(2,'select public.quartermaster84w_receive($1,$2,$3,$4,1,50)',[uid(106),sku,supplier,'86A-INITIAL']),{code:'23505'});
 const pack=(n,g,r,action)=>write(2,'select public.quartermaster84w_pack($1,$2,$3,$4,$5)',[other,uid(n),g,r,action]);
 await pack(107,0,0,{kind:'reserve',sku});
 await assert.rejects(run(108,await revision(),'archive'),{code:'23514'});
 await assert.rejects(run(109,await revision(batch),'stocktake-out',{quantity:4},batch),{code:'23514'});
 await assert.rejects(run(110,await revision(),'edit',{...rename,tare:11}),{code:'23514'});
 await pack(111,1,0,{kind:'pick',component:'fixture-staging-pot',quantity:2});
 await pack(112,1,1,{kind:'complete',purchase:batch,mm:[40,30,20],grams:75,format:'large-letter',estimate:130});
 const correction=await run(113,await revision(batch),'batch-cost',{totalMinor:230,reference:'86A-COST-REMAINDER'},batch);
 assert.equal(correction.physical,3);
 assert.equal(correction.batch.usedMinor,50);
 assert.equal(correction.batch.totalMinor,200);
 assert.equal(correction.batch.remaining,0);
 assert.equal(correction.replacement.totalMinor,180);
 assert.equal(correction.replacement.remaining,3);
 assert.equal((await db.query('select purchase_id,actual_material_minor from quartermaster79.packing where order_id=$1',[other])).rows[0].purchase_id,batch);
 assert.equal((await db.query("select count(*)::int n from quartermaster79.movement where sku=$1 and kind='purchase'",[sku])).rows[0].n,1);
 await assert.rejects(run(114,await revision(batch),'reverse-receipt',{},batch),{code:'23514'});
 assert.equal((await run(115,await revision(uid(113)),'supplier-return',{quantity:1},uid(113))).physical,2);
 assert.equal((await run(116,await revision(),'archive')).archived,true);
 await assert.rejects(write(2,'select public.quartermaster84w_receive($1,$2,$3,$4,1,50)',[uid(117),sku,supplier,'86A-ARCHIVED']),{code:'23514'});
 assert.equal((await run(118,await revision(),'reactivate')).archived,false);
 const extra=uid(119);
 await run(119,await revision(),'stocktake-in',{supplier,reference:'86A-FOUND',quantity:2,totalMinor:100});
 const beforeUndo=await read(extra);
 assert.equal((await run(120,beforeUndo.revision,'reverse-receipt',{},extra)).physical,2);
 assert.equal((await read(extra)).state.batch.remaining,0);
 const history=await read();
 assert.equal(history.history[0].action,'reverse-receipt');
 assert.ok(history.history.every(a=>a.reason==='Isolated acceptance reason'));
 assert.ok(history.history.some(a=>a.action==='opening'));
 await assert.rejects(call(2,'select * from quartermaster86.inventory_audit'),{code:'42501'});
 console.log('PASS 86A immutable identities, old-reference claims, idempotent updates, stale/reservation guards, audited counts, receipt reversal and cost reallocation');
}
