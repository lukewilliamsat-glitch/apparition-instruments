import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {forgeCircuit} from '../dist/circuit-forge/model.mjs';
import {forgeDiagram} from '../dist/circuit-forge/presentation.mjs';
import {drawCircuit} from '../dist/wiring-generator/render.mjs';
import {routeSemantics} from '../dist/wiring-generator/routing.mjs';
import {net} from '../dist/wiring-generator/model.mjs';

const circuit=forgeCircuit({bleed:'duncan'}).circuit;
const before=structuredClone(circuit),roles=routeSemantics(circuit);
const wire=(svg,id)=>svg.match(new RegExp(`<g class="wire [^"]*" data-wire="${id}"[^>]*>`))?.[0];
const all=drawCircuit(circuit),signal=drawCircuit(circuit,{filter:'signal'}),ground=drawCircuit(circuit,{filter:'ground'}),tone=drawCircuit(circuit,{filter:'tone'}),aux=drawCircuit(circuit,{filter:'auxiliary'});
assert.equal(roles.get('jackSignal').role,'signal');
assert.equal(roles.get('jackGround').role,'ground');
assert.equal(roles.get('neckToneFeed').role,'tone');
assert.equal(roles.get('neckBleedIn').role,'auxiliary');
assert.equal(roles.get('toggleJoin').role,'switch');
assert.notEqual(roles.get('jackSignal').net,roles.get('jackGround').net);
assert(!net(circuit,'jack.tip').has('jack.sleeve'));
for(const id of ['jackSignal','jackGround','neckToneFeed','neckBleedIn','toggleJoin'])assert(wire(all,id).includes(`data-route-role="${roles.get(id).role}"`));
assert(wire(signal,'jackSignal').includes('data-view-state="active"'));
assert(wire(signal,'jackGround').includes('data-view-state="muted"'));
assert(wire(ground,'jackGround').includes('data-view-state="active"'));
assert(wire(ground,'jackSignal').includes('data-view-state="muted"'));
assert(wire(tone,'neckToneFeed').includes('data-view-state="active"'));
assert(wire(tone,'neckBleedIn').includes('data-view-state="active"'),'existing Generator Tone includes treble bleed');
assert(wire(aux,'neckBleedIn').includes('data-view-state="active"'));
assert(wire(aux,'neckToneFeed').includes('data-view-state="muted"'));
assert(wire(drawCircuit(circuit,{filter:'switching'}),'toggleJoin').includes('data-view-state="active"'));
const traced=drawCircuit(circuit,{filter:'ground',selection:{kind:'path',refs:[...net(circuit,'jack.tip')]}});
assert(wire(traced,'jackSignal').includes('data-view-state="traced"'),'explicit trace wins over ground filter');
assert(wire(traced,'jackGround').includes('data-view-state="muted"'));
assert(traced.includes('[data-view-state=traced] .wire-line{stroke-width:4.5}'));
assert(forgeDiagram(circuit,{filter:'ground'}).includes('data-route-role="ground"'));
assert.deepEqual(circuit,before,'view rendering does not alter circuit topology or state');
assert.equal(drawCircuit(circuit,{filter:'ground'}),ground,'same circuit and role view is deterministic');
const html=await readFile('dist/circuit-forge/index.html','utf8'),app=await readFile('dist/circuit-forge/app.mjs','utf8');
for(const role of ['all','signal','ground','tone','auxiliary'])assert(html.includes(`data-role-view="${role}"`));
assert(app.includes('filter:roleView'));
assert(app.includes("setAttribute('aria-pressed',String(option===button))"));
console.log('Shared semantic roles, view filters, trace precedence and Forge controls PASS');
